"""Data structures for rag-eval datasets."""

from __future__ import annotations

from dataclasses import dataclass, field

ChunkMap = dict[str, str]


@dataclass
class Case:
    """A single evaluation case: one question through a RAG pipeline.

    Attributes:
        id: Unique identifier for the case.
        question: The user question sent to the RAG pipeline.
        retrieved_chunk_ids: Chunk ids returned by the retriever, in rank order
            (best/first result first).
        gold_chunk_ids: Chunk ids that are considered relevant ("ground truth")
            for this question.
        answer: The text generated by the pipeline's generator/LLM.
        chunk_texts: Mapping of chunk id -> chunk text, for every chunk id
            referenced by ``retrieved_chunk_ids`` or ``gold_chunk_ids`` that has
            known text. Used for groundedness and context-utilization scoring.
        retrieved_scores: Optional retriever scores parallel to
            ``retrieved_chunk_ids`` (same length, same order). Used only to
            document/attach retriever confidence; ranking is always taken from
            the order of ``retrieved_chunk_ids`` itself.
    """

    id: str
    question: str
    retrieved_chunk_ids: list[str]
    gold_chunk_ids: list[str]
    answer: str
    chunk_texts: ChunkMap = field(default_factory=dict)
    retrieved_scores: list[float] | None = None

    def __post_init__(self) -> None:
        if self.retrieved_scores is not None and len(self.retrieved_scores) != len(
            self.retrieved_chunk_ids
        ):
            raise ValueError(
                f"case {self.id!r}: retrieved_scores length "
                f"({len(self.retrieved_scores)}) must match retrieved_chunk_ids "
                f"length ({len(self.retrieved_chunk_ids)})"
            )

    def context_text(self, chunk_ids: list[str] | None = None) -> str:
        """Concatenate the text of the given chunk ids (default: all retrieved)."""
        ids = chunk_ids if chunk_ids is not None else self.retrieved_chunk_ids
        return "\n".join(self.chunk_texts[c] for c in ids if c in self.chunk_texts)
